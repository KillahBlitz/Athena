-- Sistema de recomendación vocacional (Athena)
-- PostgreSQL 13 o posterior.
-- Ejecutar dentro de la base de datos destinada al proyecto.
-- Modelo actualizado: incluye cuestionarios normalizados, tipo_criterio, tipo_riasec
-- y estructura de carreras con objetivos integrados.

-- ==========================================
-- PARTE 1: Áreas, Cuestionarios, Carreras, Escuelas y Criterios
-- ==========================================

BEGIN;

-- Tabla de áreas académicas
CREATE TABLE public.areas (
    area_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_area VARCHAR(200) NOT NULL
);

-- Tabla de tipo RIASEC (clasificación de preguntas y criterios)
CREATE TABLE public.tipos_riasec (
    riasec_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_riasec VARCHAR(100) NOT NULL
);

-- Tabla normalizada de preguntas
CREATE TABLE public.pregunta_cuestionario (
    pregunta_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    riasec_id INTEGER NOT NULL,
    texto_pregunta TEXT NOT NULL,
    CONSTRAINT fk_pregunta_riasec
        FOREIGN KEY (riasec_id) REFERENCES public.tipos_riasec (riasec_id)
);

-- Tabla de cuestionarios (relaciona área con pregunta)
CREATE TABLE public.cuestionarios (
    cuestionario_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id INTEGER NOT NULL,
    pregunta_id INTEGER NOT NULL,
    CONSTRAINT fk_cuestionario_area
        FOREIGN KEY (area_id) REFERENCES public.areas (area_id),
    CONSTRAINT fk_cuestionario_pregunta
        FOREIGN KEY (pregunta_id) REFERENCES public.pregunta_cuestionario (pregunta_id)
);

-- Tabla de carreras con objetivos integrados
CREATE TABLE public.carreras (
    carrera_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area_id INTEGER NOT NULL,
    nom_carrera VARCHAR(200) NOT NULL,
    origina_objetivo TEXT NOT NULL,
    objetivo TEXT NOT NULL,
    pregunta_objetivo VARCHAR(200),
    CONSTRAINT fk_carreras_area
        FOREIGN KEY (area_id) REFERENCES public.areas (area_id)
);

-- Tabla de escuelas
CREATE TABLE public.escuelas (
    escuela_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom_escuela VARCHAR(200) NOT NULL
);

-- Tabla de relación escuela-carreras (M:N)
CREATE TABLE public.escuela_carrera (
    id_escuela INTEGER NOT NULL,
    id_carrera INTEGER NOT NULL,
    CONSTRAINT pk_escuela_carreras PRIMARY KEY (id_escuela, id_carrera),
    CONSTRAINT fk_escuela_carreras_escuela
        FOREIGN KEY (id_escuela) REFERENCES public.escuelas (escuela_id),
    CONSTRAINT fk_escuela_carreras_carrera
        FOREIGN KEY (id_carrera) REFERENCES public.carreras (carrera_id)
);

-- Tabla de tipo de criterio
CREATE TABLE public.tipos_criterio (
    type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    desc_criterio TEXT NOT NULL
);

-- Tabla de criterios con relaciones a tipo_criterio y tipo_riasec
CREATE TABLE public.criterios (
    criterio_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    carrera_id INTEGER NOT NULL,
    type_id INTEGER NOT NULL,
    riasec_id INTEGER NOT NULL,
    desc_criterio TEXT NOT NULL,
    resumen_criterio VARCHAR(100) NOT NULL,
    type_extraction TEXT,
    CONSTRAINT fk_criterio_carrera
        FOREIGN KEY (carrera_id) REFERENCES public.carreras (carrera_id),
    CONSTRAINT fk_criterio_tipo
        FOREIGN KEY (type_id) REFERENCES public.tipos_criterio (type_id),
    CONSTRAINT fk_criterio_riasec
        FOREIGN KEY (riasec_id) REFERENCES public.tipos_riasec (riasec_id)
);

COMMIT;

-- ==========================================
-- PARTE 2: Usuarios, Resultados, Criterios y Objetivos
-- ==========================================

BEGIN;

-- Tabla de usuarios
CREATE TABLE public.usuarios (
    usuario_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid_usuario TEXT NOT NULL UNIQUE,
    area_id INTEGER,
    nombre_usuario VARCHAR(200) NOT NULL,
    correo_usuario VARCHAR(150) NOT NULL,
    estatus_id INTEGER NOT NULL,
    CONSTRAINT fk_usuario_area
        FOREIGN KEY (area_id) REFERENCES public.areas (area_id)
);

-- Tabla de resultados (usa usuario_id INTEGER en lugar de uuid)
CREATE TABLE public.resultados (
    id_resultado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id INTEGER NOT NULL,
    carrera_id INTEGER NOT NULL,
    porc_coincidencia FLOAT NOT NULL,
    CONSTRAINT fk_resultados_usuario
        FOREIGN KEY (usuario_id) REFERENCES public.usuarios (usuario_id),
    CONSTRAINT fk_resultados_carrera
        FOREIGN KEY (carrera_id) REFERENCES public.carreras (carrera_id)
);

-- Tabla de usuario_criterio (relación M:N con repeticiones)
CREATE TABLE public.usuario_criterio (
    usuario_id INTEGER NOT NULL,
    criterio_id INTEGER NOT NULL,
    repeticiones INTEGER NOT NULL,
    porc_coincidencia FLOAT NOT NULL,
    CONSTRAINT pk_usuario_criterio PRIMARY KEY (usuario_id, criterio_id, repeticiones),
    CONSTRAINT fk_usuario_criterio_usuario
        FOREIGN KEY (usuario_id) REFERENCES public.usuarios (usuario_id),
    CONSTRAINT fk_usuario_criterio_criterio
        FOREIGN KEY (criterio_id) REFERENCES public.criterios (criterio_id)
);

-- Tabla de puntaje de objetivos
CREATE TABLE public.puntaje_objetivo (
    usuario_id INTEGER NOT NULL,
    carrera_id INTEGER NOT NULL,
    porc_objetivo FLOAT NOT NULL,
    CONSTRAINT pk_puntaje_objetivo PRIMARY KEY (usuario_id, carrera_id),
    CONSTRAINT fk_puntaje_objetivo_usuario
        FOREIGN KEY (usuario_id) REFERENCES public.usuarios (usuario_id),
    CONSTRAINT fk_puntaje_objetivo_carrera
        FOREIGN KEY (carrera_id) REFERENCES public.carreras (carrera_id)
);

COMMIT;

-- ==========================================
-- ÍNDICES RECOMENDADOS PARA MEJOR RENDIMIENTO
-- ==========================================

BEGIN;

-- Índices en columnas de búsqueda frecuente
CREATE INDEX idx_usuario_uuid ON public.usuarios(uuid_usuario);
CREATE INDEX idx_usuario_area ON public.usuarios(area_id);
CREATE INDEX idx_carreras_area ON public.carreras(area_id);
CREATE INDEX idx_criterio_carrera ON public.criterios(carrera_id);
CREATE INDEX idx_resultados_usuario ON public.resultados(usuario_id);
CREATE INDEX idx_resultados_carrera ON public.resultados(carrera_id);
CREATE INDEX idx_cuestionario_pregunta ON public.cuestionarios(pregunta_id);

COMMIT;
